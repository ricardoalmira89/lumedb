/// Index column: quoted if it is a table column; otherwise it is an expression.
fn index_col(kind: DbKind, t: &TableDesign, c: &str) -> String {
    if t.columns.iter().any(|col| col.name == c) {
        kind.quote_one(c)
    } else {
        c.to_string()
    }
}

fn col_list(kind: DbKind, cols: &[String]) -> String {
    cols.iter().map(|c| kind.quote_one(c)).collect::<Vec<_>>().join(", ")
}

fn is_serial(ty: &str) -> bool {
    matches!(ty.to_ascii_lowercase().as_str(), "serial" | "bigserial" | "smallserial")
}

/// Column definition. `inline_pk` only for SQLite with `INTEGER PRIMARY KEY AUTOINCREMENT`.
pub fn column_sql(kind: DbKind, c: &ColumnDef, inline_pk: bool) -> String {
    let mut out = format!("{} {}", kind.quote_one(&c.name), c.data_type.trim());
    match kind {
        DbKind::Sqlite => {
            if inline_pk {
                out.push_str(" PRIMARY KEY");
                if c.auto_increment {
                    out.push_str(" AUTOINCREMENT");
                }
            }
            if !c.nullable {
                out.push_str(" NOT NULL");
            }
            if !c.default.trim().is_empty() {
                out.push_str(&format!(" DEFAULT {}", sqlite_default(&c.default)));
            }
        }
        DbKind::Postgres => {
            if c.auto_increment && !is_serial(&c.data_type) {
                out.push_str(" GENERATED BY DEFAULT AS IDENTITY");
            }
            if !c.nullable {
                out.push_str(" NOT NULL");
            }
            if !c.default.trim().is_empty() && !c.auto_increment {
                out.push_str(&format!(" DEFAULT {}", c.default.trim()));
            }
        }
        DbKind::Mysql => {
            out.push_str(if c.nullable { " NULL" } else { " NOT NULL" });
            if !c.default.trim().is_empty() {
                out.push_str(&format!(" DEFAULT {}", c.default.trim()));
            }
            if c.auto_increment {
                out.push_str(" AUTO_INCREMENT");
            }
            if !c.comment.is_empty() {
                out.push_str(&format!(" COMMENT {}", kind.quote_literal(&c.comment)));
            }
        }
    }
    out
}

/// SQLite requires parentheses for default expressions that are not literals.
fn sqlite_default(d: &str) -> String {
    let d = d.trim();
    let literal = d.starts_with('\'')
        || d.parse::<f64>().is_ok()
        || matches!(d.to_ascii_uppercase().as_str(), "NULL" | "CURRENT_TIMESTAMP" | "CURRENT_DATE" | "CURRENT_TIME" | "TRUE" | "FALSE")
        || d.starts_with('(');
    if literal {
        d.to_string()
    } else {
        format!("({d})")
    }
}

fn fk_sql(kind: DbKind, fk: &ForeignKeyDef) -> String {
    let mut out = String::new();
    if !fk.name.is_empty() && kind != DbKind::Sqlite {
        out.push_str(&format!("CONSTRAINT {} ", kind.quote_one(&fk.name)));
    }
    let target = if kind == DbKind::Sqlite || fk.ref_schema.is_empty() { kind.quote_one(&fk.ref_table) } else { kind.qualified(&fk.ref_schema, &fk.ref_table) };
    out.push_str(&format!("FOREIGN KEY ({}) REFERENCES {target} ({})", col_list(kind, &fk.columns), col_list(kind, &fk.ref_columns)));
    for (what, action) in [("DELETE", &fk.on_delete), ("UPDATE", &fk.on_update)] {
        if !action.is_empty() && !action.eq_ignore_ascii_case("NO ACTION") {
            out.push_str(&format!(" ON {what} {}", action.to_uppercase()));
        }
    }
    out
}

fn index_sql(kind: DbKind, t: &TableDesign, i: &IndexDef) -> String {
    let cols = i.columns.iter().map(|c| index_col(kind, t, c)).collect::<Vec<_>>().join(", ");
    let unique = if i.unique { "UNIQUE " } else { "" };
    let table = kind.qualified(&t.schema, &t.name);
    match kind {
        DbKind::Postgres if !i.method.is_empty() && !i.method.eq_ignore_ascii_case("btree") => {
            format!("CREATE {unique}INDEX {} ON {table} USING {} ({cols})", kind.quote_one(&i.name), i.method)
        }
        // In SQLite the index lives in the table's schema.
        DbKind::Sqlite => format!("CREATE {unique}INDEX {} ON {} ({cols})", kind.qualified(&t.schema, &i.name), kind.quote_one(&t.name)),
        _ => format!("CREATE {unique}INDEX {} ON {table} ({cols})", kind.quote_one(&i.name)),
    }
}

fn drop_index_sql(kind: DbKind, t: &TableDesign, name: &str) -> String {
    match kind {
        DbKind::Mysql => format!("DROP INDEX {} ON {}", kind.quote_one(name), kind.qualified(&t.schema, &t.name)),
        _ => format!("DROP INDEX {}", kind.qualified(&t.schema, name)),
    }
}

fn sqlite_inline_pk(t: &TableDesign) -> Option<&ColumnDef> {
    let pk: Vec<&ColumnDef> = t.columns.iter().filter(|c| c.primary_key).collect();
    match pk.as_slice() {
        [c] if c.auto_increment || c.data_type.eq_ignore_ascii_case("integer") => Some(c),
        _ => None,
    }
}

/// `CREATE TABLE` plus indexes and comments.
pub fn create_table(kind: DbKind, t: &TableDesign) -> Vec<String> {
    let inline = if kind == DbKind::Sqlite { sqlite_inline_pk(t).map(|c| c.name.clone()) } else { None };
    let mut lines: Vec<String> = t.columns.iter().map(|c| format!("  {}", column_sql(kind, c, inline.as_deref() == Some(&c.name)))).collect();
    let pk = t.primary_key();
    if !pk.is_empty() && inline.is_none() {
        let pk: Vec<String> = pk.iter().map(|s| s.to_string()).collect();
        let name = if kind == DbKind::Postgres && !t.pk_name.is_empty() { format!("CONSTRAINT {} ", kind.quote_one(&t.pk_name)) } else { String::new() };
        lines.push(format!("  {name}PRIMARY KEY ({})", col_list(kind, &pk)));
    }
    for fk in &t.foreign_keys {
        lines.push(format!("  {}", fk_sql(kind, fk)));
    }
    let mut create = format!("CREATE TABLE {} (\n{}\n)", kind.qualified(&t.schema, &t.name), lines.join(",\n"));
    if kind == DbKind::Mysql && !t.comment.is_empty() {
        create.push_str(&format!(" COMMENT = {}", kind.quote_literal(&t.comment)));
    }
    let mut out = vec![create + ";"];
    for i in &t.indexes {
        out.push(index_sql(kind, t, i) + ";");
    }
    if kind == DbKind::Postgres {
        out.extend(pg_comments(t, None));
    }
    out
}

fn pg_comments(t: &TableDesign, old: Option<&TableDesign>) -> Vec<String> {
    let k = DbKind::Postgres;
    let table = k.qualified(&t.schema, &t.name);
    let lit = |c: &str| if c.is_empty() { "NULL".to_string() } else { k.quote_literal(c) };
    let mut out = Vec::new();
    if old.map_or(!t.comment.is_empty(), |o| o.comment != t.comment) {
        out.push(format!("COMMENT ON TABLE {table} IS {};", lit(&t.comment)));
    }
    for c in &t.columns {
        let before = old.and_then(|o| c.original_name.as_ref().and_then(|n| o.columns.iter().find(|oc| &oc.name == n)));
        if before.map_or(!c.comment.is_empty(), |b| b.comment != c.comment) {
            out.push(format!("COMMENT ON COLUMN {table}.{} IS {};", k.quote_one(&c.name), lit(&c.comment)));
        }
    }
    out
}

/// Statements to go from `old` to `new`. Empty if there are no changes.
pub fn alter_table(kind: DbKind, old: &TableDesign, new: &TableDesign) -> Vec<String> {
    match kind {
        DbKind::Postgres => alter_postgres(old, new),
        DbKind::Mysql => alter_mysql(old, new),
        DbKind::Sqlite => alter_sqlite(old, new),
    }
}

struct Diff<'a> {
    dropped_cols: Vec<&'a ColumnDef>,
    added_cols: Vec<(usize, &'a ColumnDef)>,
    /// (before, after)
    changed_cols: Vec<(&'a ColumnDef, &'a ColumnDef)>,
    pk_changed: bool,
    dropped_idx: Vec<&'a IndexDef>,
    added_idx: Vec<&'a IndexDef>,
    dropped_fk: Vec<&'a ForeignKeyDef>,
    added_fk: Vec<&'a ForeignKeyDef>,
}

fn diff<'a>(old: &'a TableDesign, new: &'a TableDesign) -> Diff<'a> {
    let kept: Vec<&String> = new.columns.iter().filter_map(|c| c.original_name.as_ref()).collect();
    let dropped_cols = old.columns.iter().filter(|c| !kept.contains(&&c.name)).collect();
    let mut added_cols = Vec::new();
    let mut changed_cols = Vec::new();
    for (i, c) in new.columns.iter().enumerate() {
        match c.original_name.as_ref().and_then(|n| old.columns.iter().find(|o| &o.name == n)) {
            None => added_cols.push((i, c)),
            Some(o) => {
                let mut a = o.clone();
                let mut b = c.clone();
                a.original_name = None;
                b.original_name = None;
                a.primary_key = false;
                b.primary_key = false;
                if a != b {
                    changed_cols.push((o, c));
                }
            }
        }
    }
    let old_pk: Vec<&str> = old.primary_key();
    let new_pk: Vec<String> = new.columns.iter().filter(|c| c.primary_key).map(|c| c.original_name.clone().unwrap_or_default()).collect();
    let pk_changed = old_pk.len() != new_pk.len()
        || old_pk.iter().zip(&new_pk).any(|(a, b)| a != b)
        || new.columns.iter().any(|c| c.primary_key && c.original_name.is_none());

    let same_idx = |a: &IndexDef, b: &IndexDef| a.columns == b.columns && a.unique == b.unique && a.name == b.name && a.method == b.method;
    let dropped_idx = old
        .indexes
        .iter()
        .filter(|o| !new.indexes.iter().any(|n| n.original_name.as_ref() == Some(&o.name) && same_idx(o, n)))
        .filter(|o| o.original_name.is_some())
        .collect();
    let added_idx = new.indexes.iter().filter(|n| !old.indexes.iter().any(|o| n.original_name.as_ref() == Some(&o.name) && same_idx(o, n))).collect();
    let same_fk = |a: &ForeignKeyDef, b: &ForeignKeyDef| {
        let mut a = a.clone();
        let mut b = b.clone();
        a.original_name = None;
        b.original_name = None;
        a == b
    };
    let dropped_fk = old.foreign_keys.iter().filter(|o| !new.foreign_keys.iter().any(|n| n.original_name.as_ref() == Some(&o.name) && same_fk(o, n))).collect();
    let added_fk = new.foreign_keys.iter().filter(|n| !old.foreign_keys.iter().any(|o| n.original_name.as_ref() == Some(&o.name) && same_fk(o, n))).collect();
    Diff { dropped_cols, added_cols, changed_cols, pk_changed, dropped_idx, added_idx, dropped_fk, added_fk }
}

fn renamed(old: &TableDesign, new: &TableDesign) -> bool {
    old.name != new.name
}

fn alter_postgres(old: &TableDesign, new: &TableDesign) -> Vec<String> {
    let k = DbKind::Postgres;
    let d = diff(old, new);
    let mut out = Vec::new();
    let mut table = k.qualified(&old.schema, &old.name);
    if renamed(old, new) {
        out.push(format!("ALTER TABLE {table} RENAME TO {};", k.quote_one(&new.name)));
        table = k.qualified(&new.schema, &new.name);
    }
    for fk in &d.dropped_fk {
        out.push(format!("ALTER TABLE {table} DROP CONSTRAINT {};", k.quote_one(&fk.name)));
    }
    for i in &d.dropped_idx {
        out.push(format!("{};", drop_index_sql(k, old, &i.name)));
    }
    if d.pk_changed && !old.primary_key().is_empty() {
        let name = if old.pk_name.is_empty() { format!("{}_pkey", old.name) } else { old.pk_name.clone() };
        out.push(format!("ALTER TABLE {table} DROP CONSTRAINT {};", k.quote_one(&name)));
    }
    for c in &d.dropped_cols {
        out.push(format!("ALTER TABLE {table} DROP COLUMN {};", k.quote_one(&c.name)));
    }
    for (o, n) in &d.changed_cols {
        let mut col = k.quote_one(&o.name);
        if o.name != n.name {
            out.push(format!("ALTER TABLE {table} RENAME COLUMN {col} TO {};", k.quote_one(&n.name)));
            col = k.quote_one(&n.name);
        }
        if o.data_type != n.data_type {
            out.push(format!("ALTER TABLE {table} ALTER COLUMN {col} TYPE {} USING {col}::{};", n.data_type, n.data_type));
        }
        if o.auto_increment != n.auto_increment {
            if n.auto_increment {
                out.push(format!("ALTER TABLE {table} ALTER COLUMN {col} ADD GENERATED BY DEFAULT AS IDENTITY;"));
            } else {
                out.push(format!("ALTER TABLE {table} ALTER COLUMN {col} DROP IDENTITY IF EXISTS;"));
            }
        }
        if o.nullable != n.nullable {
            let what = if n.nullable { "DROP" } else { "SET" };
            out.push(format!("ALTER TABLE {table} ALTER COLUMN {col} {what} NOT NULL;"));
        }
        if o.default != n.default && !n.auto_increment {
            if n.default.trim().is_empty() {
                out.push(format!("ALTER TABLE {table} ALTER COLUMN {col} DROP DEFAULT;"));
            } else {
                out.push(format!("ALTER TABLE {table} ALTER COLUMN {col} SET DEFAULT {};", n.default.trim()));
            }
        }
    }
    for (_, c) in &d.added_cols {
        out.push(format!("ALTER TABLE {table} ADD COLUMN {};", column_sql(k, c, false)));
    }
    if d.pk_changed {
        let pk: Vec<String> = new.primary_key().iter().map(|s| s.to_string()).collect();
        if !pk.is_empty() {
            out.push(format!("ALTER TABLE {table} ADD PRIMARY KEY ({});", col_list(k, &pk)));
        }
    }
    let target = TableDesign { name: new.name.clone(), ..new.clone() };
    for i in &d.added_idx {
        out.push(format!("{};", index_sql(k, &target, i)));
    }
    for fk in &d.added_fk {
        out.push(format!("ALTER TABLE {table} ADD {};", fk_sql(k, fk)));
    }
    out.extend(pg_comments(new, Some(old)));
    out
}

fn alter_mysql(old: &TableDesign, new: &TableDesign) -> Vec<String> {
    let k = DbKind::Mysql;
    let d = diff(old, new);
    let mut out = Vec::new();
    let mut table = k.qualified(&old.schema, &old.name);
    if renamed(old, new) {
        let to = k.qualified(&new.schema, &new.name);
        out.push(format!("RENAME TABLE {table} TO {to};"));
        table = to;
    }
    if !d.dropped_fk.is_empty() {
        let parts: Vec<String> = d.dropped_fk.iter().map(|f| format!("DROP FOREIGN KEY {}", k.quote_one(&f.name))).collect();
        out.push(format!("ALTER TABLE {table} {};", parts.join(", ")));
    }
    let mut parts = Vec::new();
    for i in &d.dropped_idx {
        parts.push(format!("DROP INDEX {}", k.quote_one(&i.name)));
    }
    if d.pk_changed && !old.primary_key().is_empty() {
        parts.push("DROP PRIMARY KEY".into());
    }
    for c in &d.dropped_cols {
        parts.push(format!("DROP COLUMN {}", k.quote_one(&c.name)));
    }
    for (o, n) in &d.changed_cols {
        parts.push(format!("CHANGE COLUMN {} {}", k.quote_one(&o.name), column_sql(k, n, false)));
    }
    for (i, c) in &d.added_cols {
        let pos = if *i == 0 { " FIRST".to_string() } else { format!(" AFTER {}", k.quote_one(&new.columns[i - 1].name)) };
        parts.push(format!("ADD COLUMN {}{pos}", column_sql(k, c, false)));
    }
    if d.pk_changed {
        let pk: Vec<String> = new.primary_key().iter().map(|s| s.to_string()).collect();
        if !pk.is_empty() {
            parts.push(format!("ADD PRIMARY KEY ({})", col_list(k, &pk)));
        }
    }
    for i in &d.added_idx {
        let cols = i.columns.iter().map(|c| index_col(k, new, c)).collect::<Vec<_>>().join(", ");
        let unique = if i.unique { "UNIQUE " } else { "" };
        parts.push(format!("ADD {unique}INDEX {} ({cols})", k.quote_one(&i.name)));
    }
    if old.comment != new.comment {
        parts.push(format!("COMMENT = {}", k.quote_literal(&new.comment)));
    }
    if !parts.is_empty() {
        out.push(format!("ALTER TABLE {table}\n  {};", parts.join(",\n  ")));
    }
    if !d.added_fk.is_empty() {
        let parts: Vec<String> = d.added_fk.iter().map(|f| format!("ADD {}", fk_sql(k, f))).collect();
        out.push(format!("ALTER TABLE {table} {};", parts.join(", ")));
    }
    out
}

fn alter_sqlite(old: &TableDesign, new: &TableDesign) -> Vec<String> {
    let k = DbKind::Sqlite;
    let d = diff(old, new);
    let only_renames = d.changed_cols.iter().all(|(o, n)| {
        let mut a = (*o).clone();
        a.name = n.name.clone();
        a.original_name = n.original_name.clone();
        a == **n
    });
    let simple = only_renames
        && !d.pk_changed
        && d.dropped_fk.is_empty()
        && d.added_fk.is_empty()
        && d.dropped_cols.iter().all(|c| !c.primary_key)
        && d.added_cols.iter().all(|(_, c)| !c.primary_key && (c.nullable || !c.default.is_empty()));

    let mut out = Vec::new();
    if simple {
        let mut table = k.qualified(&old.schema, &old.name);
        if renamed(old, new) {
            out.push(format!("ALTER TABLE {table} RENAME TO {};", k.quote_one(&new.name)));
            table = k.qualified(&new.schema, &new.name);
        }
        for i in &d.dropped_idx {
            out.push(format!("{};", drop_index_sql(k, old, &i.name)));
        }
        for c in &d.dropped_cols {
            out.push(format!("ALTER TABLE {table} DROP COLUMN {};", k.quote_one(&c.name)));
        }
        for (o, n) in &d.changed_cols {
            out.push(format!("ALTER TABLE {table} RENAME COLUMN {} TO {};", k.quote_one(&o.name), k.quote_one(&n.name)));
        }
        for (_, c) in &d.added_cols {
            out.push(format!("ALTER TABLE {table} ADD COLUMN {};", column_sql(k, c, false)));
        }
        for i in &d.added_idx {
            out.push(format!("{};", index_sql(k, new, i)));
        }
        return out;
    }

    // Native renames first (that way SQLite rewrites views and triggers)…
    let renames: Vec<(String, String)> = d.changed_cols.iter().filter(|(o, n)| o.name != n.name).map(|(o, n)| (o.name.clone(), n.name.clone())).collect();
    if !renames.is_empty() {
        let table = k.qualified(&old.schema, &old.name);
        for (from, to) in &renames {
            out.push(format!("ALTER TABLE {table} RENAME COLUMN {} TO {};", k.quote_one(from), k.quote_one(to)));
        }
        let mut old2 = old.clone();
        for c in &mut old2.columns {
            if let Some((_, to)) = renames.iter().find(|(f, _)| *f == c.name) {
                c.name = to.clone();
            }
        }
        let mut new2 = new.clone();
        for c in &mut new2.columns {
            if let Some((_, to)) = renames.iter().find(|(f, _)| Some(f) == c.original_name.as_ref()) {
                c.original_name = Some(to.clone());
            }
        }
        out.extend(alter_sqlite(&old2, &new2));
        return out;
    }

    // …and then the rebuild: new table, data copy, drop and rename.
    let tmp = format!("_lumedb_new_{}", new.name);
    let mut staged = new.clone();
    staged.name = tmp.clone();
    staged.indexes.clear();
    let copied: Vec<(&String, &String)> = new.columns.iter().filter_map(|c| c.original_name.as_ref().map(|o| (&c.name, o))).collect();
    // legacy_alter_table stops the rename from validating views that point to the table.
    out.push("PRAGMA foreign_keys = OFF;".into());
    out.push("PRAGMA legacy_alter_table = ON;".into());
    out.extend(create_table(k, &staged));
    if !copied.is_empty() {
        let to: Vec<String> = copied.iter().map(|(n, _)| k.quote_one(n)).collect();
        let from: Vec<String> = copied.iter().map(|(_, o)| k.quote_one(o)).collect();
        out.push(format!(
            "INSERT INTO {} ({}) SELECT {} FROM {};",
            k.qualified(&new.schema, &tmp),
            to.join(", "),
            from.join(", "),
            k.qualified(&old.schema, &old.name)
        ));
    }
    out.push(format!("DROP TABLE {};", k.qualified(&old.schema, &old.name)));
    out.push(format!("ALTER TABLE {} RENAME TO {};", k.qualified(&new.schema, &tmp), k.quote_one(&new.name)));
    for i in &new.indexes {
        out.push(format!("{};", index_sql(k, new, i)));
    }
    out.push("PRAGMA legacy_alter_table = OFF;".into());
    out.push("PRAGMA foreign_keys = ON;".into());
    out
}
