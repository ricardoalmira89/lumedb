//! Table design model and diff-based `CREATE` / `ALTER` generation.

use crate::config::DbKind;

#[derive(Debug, Clone, PartialEq, Default)]
pub struct ColumnDef {
    pub name: String,
    pub data_type: String,
    pub nullable: bool,
    /// SQL expression as is (`'text'`, `0`, `CURRENT_TIMESTAMP`…). Empty = no default value.
    pub default: String,
    pub primary_key: bool,
    pub auto_increment: bool,
    pub comment: String,
    /// Name in the database; `None` if the column is new.
    pub original_name: Option<String>,
}

#[derive(Debug, Clone, PartialEq, Default)]
pub struct IndexDef {
    pub name: String,
    /// Column names or expressions.
    pub columns: Vec<String>,
    pub unique: bool,
    /// Method (BTREE, HASH, gin…). Empty = default.
    pub method: String,
    pub original_name: Option<String>,
}

#[derive(Debug, Clone, PartialEq, Default)]
pub struct ForeignKeyDef {
    pub name: String,
    pub columns: Vec<String>,
    pub ref_schema: String,
    pub ref_table: String,
    pub ref_columns: Vec<String>,
    pub on_update: String,
    pub on_delete: String,
    pub original_name: Option<String>,
}

#[derive(Debug, Clone, PartialEq, Default)]
pub struct TableDesign {
    pub schema: String,
    pub name: String,
    pub original_name: Option<String>,
    pub columns: Vec<ColumnDef>,
    pub indexes: Vec<IndexDef>,
    pub foreign_keys: Vec<ForeignKeyDef>,
    pub comment: String,
    /// Name of the primary key constraint (PostgreSQL).
    pub pk_name: String,
}

impl TableDesign {
    pub fn primary_key(&self) -> Vec<&str> {
        self.columns.iter().filter(|c| c.primary_key).map(|c| c.name.as_str()).collect()
    }
}

